package basics;

public class ArithmeticOperators {

    public static void main(String[] args)
    {
        int a=20;
        int b=30;

        System.out.println("The Addition of number is"+(a+b));
        System.out.println("The sub of number is"+(b-a));
        System.out.println("The Addition of number is"+(a*b));
        System.out.println("The Addition of number is"+(b/a));
    }
}
